function copyResult(result: any) {

  const text =
    `${result.matchedAddress}\nZIP Code: ${result.zip}`

  navigator.clipboard.writeText(text)
    .then(() => alert('Address copied!'))

}


function shareAddressResult(
  result: any,
  zipDetails: any
) {

  const text =
`📮 Address to ZIP Result

${result.matchedAddress}

ZIP Code: ${result.zip}
${zipDetails?.county ? `County: ${zipDetails.county}` : ''}
${zipDetails?.tzLabel ? `Timezone: ${zipDetails.tzLabel}` : ''}

Find a ZIP code:
tooltrio.com/zip/address-to-zip`

  if (navigator.share) {

    navigator.share({
      title: 'Address to ZIP',
      text
    })

  } else {

    navigator.clipboard
      .writeText(text)
      .then(() =>
        alert('Result copied!')
      )

  }
}


function downloadAddressResult(
  result: any,
  zipDetails: any
) {

  const text =
`TOOLTRIO — Address to ZIP Report

Matched Address
${result.matchedAddress}

ZIP Code
${result.zip}

City: ${zipDetails?.city || 'N/A'}
State: ${zipDetails?.state || 'N/A'}
County: ${zipDetails?.county || 'N/A'}
Timezone: ${zipDetails?.tzLabel || zipDetails?.timezone || 'N/A'}
Area Code: ${zipDetails?.areaCode || 'N/A'}
ZIP Type: ${zipDetails?.type || 'N/A'}
Population: ${zipDetails?.population || 'N/A'}

Latitude: ${result.coordinates?.lat ?? zipDetails?.lat ?? 'N/A'}
Longitude: ${result.coordinates?.lng ?? zipDetails?.lng ?? 'N/A'}

Generated by ToolTrio
tooltrio.com/zip/address-to-zip
`

  const blob =
    new Blob(
      [text],
      { type: 'text/plain' }
    )

  const url =
    URL.createObjectURL(blob)

  const a =
    document.createElement('a')

  a.href = url

  a.download =
    `address-to-zip-${result.zip}.txt`

  a.click()

  URL.revokeObjectURL(url)

}


