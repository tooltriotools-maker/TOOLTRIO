async function lookup() {

   if (loading) return

  if (street.trim().length < 3) {
    setError(
      'Please enter a valid street address.'
    )
    return
  }

  if (city.trim().length < 2) {
    setError(
      'Please enter a valid city.'
    )
    return
  }

  if (!state) {
    setError(
      'Please select a state.'
    )
    return
  }
  try {

    setLoading(true)
    setError('')
    setResult(null)
    setZipDetails(null)

    // STEP 1:
    // Address → ZIP

    const params = new URLSearchParams({
      street: street.trim(),
      city: city.trim(),
      state: state.trim().toUpperCase(),
    })

    const addressResponse = await fetch(
      `/api/zip/address?${params.toString()}`
    )

    const addressData =
      await addressResponse.json()

    if (!addressResponse.ok) {
      throw new Error(
        addressData.error ||
        'Address could not be found.'
      )
    }

    setResult(addressData)


    // STEP 2:
    // ZIP → full ZIP information

    const zipResponse = await fetch(
      `/api/zip/lookup?zip=${addressData.zip}`
    )

    const zipData =
      await zipResponse.json()

    if (zipResponse.ok) {
      setZipDetails(zipData)
    }

  } catch (err: any) {

    setError(
      err?.message ||
      'Unable to look up this address.'
    )

  } finally {

    setLoading(false)

  }
}

