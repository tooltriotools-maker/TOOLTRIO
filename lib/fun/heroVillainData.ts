function rand<T>(arr: T[]): T { return arr[Math.floor(Math.random() * arr.length)] }

export function generateHeroName(): string {
  // 60% compound, 40% single-word style
  if (Math.random() < 0.6) {
    return rand(HERO_PREFIX) + rand(HERO_SUFFIX)
  }
  const prefixes = ['The ','','Captain ','Agent ','']
  return rand(prefixes) + rand(HERO_PREFIX) + (Math.random() < 0.3 ? ' ' + rand(HERO_SUFFIX) : '')
}

export function generateVillainName(): string {
  if (Math.random() < 0.5) {
    return rand(VILLAIN_PREFIX) + rand(VILLAIN_SUFFIX)
  }
  const titles = ['Doctor ','Professor ','Lord ','Master ','The ','']
  return rand(titles) + rand(VILLAIN_PREFIX) + (Math.random() < 0.4 ? ' ' + rand(VILLAIN_SUFFIX) : '')
}

export function generateFantasyName(race: string = 'human'): string {
  const prefixPool = FANTASY_PREFIXES[race] || FANTASY_PREFIXES.human
  const suffixPool = FANTASY_SUFFIXES[race] || FANTASY_SUFFIXES.human
  return rand(prefixPool) + rand(suffixPool)
}

