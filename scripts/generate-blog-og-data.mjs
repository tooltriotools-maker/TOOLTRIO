import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const reportPath = path.join(root, 'reports', 'blog-audit-report.json')
const output = path.join(root, 'lib', 'blog', 'blogOgData.ts')

if (!fs.existsSync(reportPath)) {
  throw new Error('Missing reports/blog-audit-report.json. Run npm run blog:audit first.')
}

const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'))
const rows = Array.isArray(report.rows) ? report.rows : []
const data = {}

for (const row of rows) {
  if (!row?.slug) continue
  data[row.slug] = {
    title: row.title ?? 'ToolTrio Blog',
    category: row.category ?? 'Guides',
    categorySlug: typeof row.categoryUrl === 'string' ? row.categoryUrl.split('/').pop() ?? '' : '',
  }
}

if (Object.keys(data).length === 0) throw new Error('No blog OG records found in audit report')

const body = `// Generated by scripts/generate-blog-og-data.mjs. Keep this file lightweight because it is imported by the Edge OG image route.\nexport interface BlogOgData { title: string; category: string; categorySlug: string }\nexport const blogOgData: Record<string, BlogOgData> = ${JSON.stringify(data)}\n`
fs.writeFileSync(output, body)
console.log(`Generated ${Object.keys(data).length} lightweight blog OG records -> ${path.relative(root, output)}`)
